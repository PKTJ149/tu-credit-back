export function findTeacherById(id: string): Teacher | undefined {
  return teachers.find((t) => t.id === id);
}

export function getTeachersByIds(ids: string[] | undefined): Teacher[] {
  if (!ids || ids.length === 0) return [];
  return ids
    .map((id) => findTeacherById(id))
    .filter((t): t is Teacher => t !== undefined);
}
