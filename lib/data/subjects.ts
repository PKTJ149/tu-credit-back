export function findSubjectsByTeacherId(id: string) {
  return subjects.filter((subject) => subject.teacherIds?.includes(id));
}

export function getSubjectsByIds(ids: string[] | undefined) {
  if (!ids || ids.length === 0) return [];
  return ids
    .map((id) => subjects.find((s) => s.id === id))
    .filter((s): s is (typeof subjects)[number] => s !== undefined);
}
